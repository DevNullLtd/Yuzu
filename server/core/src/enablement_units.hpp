/// The derived overlay: units + recorded non-units (sorted by name) and the
/// validated requirement edges as (unit, required) name pairs.
struct UnitOverlay {
    std::vector<Unit> units;
    std::vector<NonUnit> non_units;
    std::vector<std::pair<std::string, std::string>> requirements;

    // ponytail: linear scans, < 300 units; index when a profile says so.
    [[nodiscard]] const Unit* find(std::string_view name) const {
        for (const auto& u : units)
            if (u.name == name)
                return &u;
        return nullptr;
    }
    [[nodiscard]] const NonUnit* find_non_unit(std::string_view name) const {
        for (const auto& n : non_units)
            if (n.name == name)
                return &n;
        return nullptr;
    }
    /// Action units contained by a plugin unit.
    [[nodiscard]] std::vector<const Unit*> actions_of(std::string_view plugin) const {
        std::vector<const Unit*> out;
        for (const auto& u : units)
            if (u.kind == UnitKind::Action && u.plugin == plugin)
                out.push_back(&u);
        return out;
    }
    /// True iff `unit` can be off on an endpoint of `os` (nullopt = unknown OS
    /// => applicable nowhere).
    [[nodiscard]] static bool applicable(const Unit& unit, std::optional<std::uint8_t> os) {
        return os && (unit.os & *os) != 0;
    }
};

[[nodiscard]] inline std::expected<UnitOverlay, std::string>
build_unit_overlay(std::initializer_list<std::span<const CommandCapability>> sources,
                   ProtectivePredicate protective,
                   std::span<const UnitOsRow> os_rows = kUnitOs,
                   std::span<const RequirementEdge> edges = kRequirements) {
    using Err = std::unexpected<std::string>;
    if (!protective)
        return Err("protective predicate required");

    std::vector<bool> os_used(os_rows.size(), false);
    UnitOverlay out;
    // Per plugin: OR of its action units' bits, and the reason of its first
    // non-unit action (used only when every action is a non-unit).
    struct PluginAcc {
        std::string name;
        std::uint8_t os{0};
        std::size_t unit_actions{0};
        NonUnitReason reason{NonUnitReason::Protective};
        bool has_reason{false};
    };
    std::vector<PluginAcc> plugins;
    auto acc_for = [&plugins](std::string_view plugin) -> PluginAcc& {
        for (auto& p : plugins)
            if (p.name == plugin)
                return p;
        plugins.push_back(PluginAcc{std::string(plugin)});
        return plugins.back();
    };

    for (const auto& src : sources) {
        for (const auto& row : src) {
            if (!is_legal_unit_plugin(row.plugin) ||
                !plugin_config::is_valid_identifier(row.action))
                return Err("catalogue pair is not a legal unit name: " + std::string(row.plugin) +
                           "." + std::string(row.action));
            const std::string name = std::string(row.plugin) + "." + std::string(row.action);
            if (out.find(name) || out.find_non_unit(name))
                return Err("duplicate catalogue pair: " + name);
            auto& acc = acc_for(row.plugin);
            std::optional<NonUnitReason> non;
            if (plugin_config::is_reserved_plugin_name(row.plugin))
                non = NonUnitReason::ReservedName;
            else if (protective(row.plugin, row.action))
                non = NonUnitReason::Protective;
            // The matrix carries rows for protective actions too; a non-unit
            // needs no os row but one that exists is not stale.
            std::optional<std::size_t> hit;
            for (std::size_t i = 0; i < os_rows.size(); ++i)
                if (os_rows[i].plugin == row.plugin && os_rows[i].action == row.action) {
                    hit = i;
                    os_used[i] = true;
                    break;
                }
            // Validated wherever a row exists, unit or not: a protective row's
            // mask is as much a data-table error as a switchable one's.
            if (hit)
                if (const auto bits = os_rows[*hit].os; bits == 0 || (bits & ~kAllOs) != 0)
                    return Err("os row has no valid OS bits: " + name);
            if (non) {
                out.non_units.push_back({name, *non});
                if (!acc.has_reason) {
                    acc.reason = *non;
                    acc.has_reason = true;
                }
                continue;
            }
            if (!hit)
                return Err("catalogue unit has no kUnitOs row: " + name +
                           " - add it to kUnitOs in server/core/src/enablement_units.hpp (mask "
                           "from the docs/os-capability-matrix.md generated block)");
            out.units.push_back({name, std::string(row.plugin), std::string(row.action),
                                 UnitKind::Action, os_rows[*hit].os});
            acc.os |= os_rows[*hit].os;
            ++acc.unit_actions;
        }
    }
    for (std::size_t i = 0; i < os_rows.size(); ++i)
        if (!os_used[i])
            return Err("unmatched os row (stale or duplicate): " +
                       std::string(os_rows[i].plugin) + "." + std::string(os_rows[i].action));

    for (const auto& p : plugins) {
        if (p.unit_actions > 0)
            out.units.push_back({p.name, p.name, {}, UnitKind::Plugin, p.os});
        else
            out.non_units.push_back({p.name, p.reason});
    }

    for (const auto& e : edges) {
        if (!out.find(e.unit) || !out.find(e.required))
            return Err("requirement edge end is not a unit: " + std::string(e.unit) + " -> " +
                       std::string(e.required));
        out.requirements.emplace_back(std::string(e.unit), std::string(e.required));
    }

    auto by_name = [](const auto& a, const auto& b) { return a.name < b.name; };
    std::sort(out.units.begin(), out.units.end(), by_name);
    std::sort(out.non_units.begin(), out.non_units.end(), by_name);
    return out;
}

