// Agent-OS bits. macOS is "darwin" everywhere in the enablement vocabulary.
inline constexpr std::uint8_t kWin = 1;
inline constexpr std::uint8_t kLin = 2;
inline constexpr std::uint8_t kMac = 4;
inline constexpr std::uint8_t kAllOs = kWin | kLin | kMac;

/// Bit for an agent-reported OS, or nullopt outside the closed vocabulary
/// (windows|linux|darwin).
[[nodiscard]] inline std::optional<std::uint8_t> os_bit(std::string_view agent_os) {
    if (!plugin_config::is_valid_agent_os(agent_os))
        return std::nullopt;
    if (agent_os == "windows")
        return kWin;
    if (agent_os == "linux")
        return kLin;
    return kMac;
}

struct UnitOsRow {
    std::string_view plugin;
    std::string_view action;
    std::uint8_t os;
};

enum class UnitKind : std::uint8_t { Plugin, Action };

struct Unit {
    std::string name;   // `plugin` or `plugin.action`
    std::string plugin;
    std::string action; // empty for a plugin unit
    UnitKind kind;
    std::uint8_t os;    // OS bits the unit is applicable on
};

enum class NonUnitReason : std::uint8_t { Protective, ReservedName };

struct NonUnit {
    std::string name;
    NonUnitReason reason;
};

/// `unit` cannot run unless `required` is on (both are unit names).
struct RequirementEdge {
    std::string_view unit;
    std::string_view required;
};

using ProtectivePredicate = bool (*)(std::string_view plugin, std::string_view action);

/// The plugin half of a unit name: a legal identifier, or a reserved control-channel
/// name. ONE definition, shared by build_unit_overlay (catalogue rows) and the loader's
/// is_unit_name_shape (enablement_resolver.hpp), so the two cannot drift apart.
[[nodiscard]] inline bool is_legal_unit_plugin(std::string_view plugin) {
    return plugin_config::is_valid_identifier(plugin) ||
           plugin_config::is_reserved_plugin_name(plugin);
}

