/**
 * enablement_units.hpp — the switchable-unit overlay (ADR-3006).
 *
 * Not a second catalogue. `build_unit_overlay` takes the SAME capability
 * fragment spans `CommandCapabilityRegistry` takes (command_capability.hpp)
 * and derives unit names from them: `<plugin>` and `<plugin>.<action>`. The
 * only data added here is per-OS applicability (`kUnitOs`) and the requirement
 * edges (`kRequirements`).
 *
 * Pure: no I/O, no clock, no globals beyond the constexpr tables below.
 *
 * Non-units (ADR-3006 D3): a protective action (the injected predicate) and
 * any action of a reserved-name plugin (`__guard__`, `__sync__`: the control
 * channel) are never units. A plugin whose every action is a non-unit is
 * itself recorded as a plugin-level non-unit with the same reason, so a rule
 * may name it and be accepted as having no effect.
 *
 * `CommandCapability::system_reserved` is deliberately NOT read here. It
 * records who the RBAC caller of a dispatch is, not whether work is
 * switchable: under D3 work the agent starts by itself obeys the same state,
 * so echo.fleet_snapshot and asset_tags.sync are ordinary units.
 *
 * PROTECTIVE SEAM (one line): the caller injects the predicate, and it is the
 * canonical protective set, `kProtectivePredicate`, which is
 * `&yuzu::protective::is_protective_action` (common/include/yuzu/protective_actions.hpp):
 * the quarantine control actions plus `__guard__.push_rules`. One predicate, never a
 * second list, so a future widening of that set removes the new action from the
 * switchable units with no edit here. `__guard__.push_rules` is also caught by the
 * reserved-name rule (the control channel), which is checked first. There is no default, so a
 * caller can never forget to choose.
 *
 * Unit names are `<plugin>` or `<plugin>.<action>` only: a catalogue row whose
 * plugin or action is not a legal identifier (the kill-switch scope grammar,
 * plugin_config_parsers.hpp) is refused, since the name is frozen by the first
 * persisted rule and by audit and export strings. Non-action kinds (capture
 * sources and the like) are not unit names until an ADR amends this grammar.
 *
 * kUnitOs PROVENANCE: hand-maintained, derived from the generated block of
 * docs/os-capability-matrix.md (support != unsupported => applicable;
 * macos => darwin). That block is regenerated by tools/capmatrix-gen and
 * checked by scripts/ci/check-capability-matrix.sh, and is never hand-edited;
 * this table is not generated by either. Its guard is
 * tests/test_enablement_os_applicability.py, which cross-checks the table
 * against the block in both directions, so a stale or mistyped row fails the
 * docs suite.
 *
 * Adding a plugin or action without a kUnitOs row makes build_unit_overlay
 * fail (and the units test with it).
 */

