/**
 * test_component_scan.cpp -- tests for the component_inventory scan
 * (agents/plugins/component_inventory/src/component_scan.hpp). The scan is driven over an in-memory
 * tree and a fake clock, with archives built as bytes by component_fixture_tree.hpp; nothing here
 * touches the host except the one POSIX-only case at the end, which materialises a small tree under
 * a yuzu_test_ temporary directory and runs the real filesystem leg over it.
 *
 * MUTATION NOTES (each assertion below FAILS if the named wiring is removed):
 *  - prepended bytes: reading a local header at the unshifted offset fails the executable-jar case
 *    (the version stays unreadable).
 *  - enumeration failure: dropping record(archive_unenumerated) fails every row of the completeness
 *    table, which would otherwise read complete with nested libraries unlisted.
 *  - count short of the directory: removing the reader's trailing-bytes check (the pos != cd.size()
 *    test in for_each_central_entry) fails the "end record counts fewer records" row.
 *  - changed archive: dropping the unchanged() check fails the "changed while read" row.
 *  - one deadline: checking the deadline only in the walk fails the budget_time case (all three
 *    archives would be opened); dropping the final clock check fails the single-archive case and the
 *    empty-tree case.
 *  - entry cap: inflating without the 64 KiB output cap fails the "lying size" case (its manifest
 *    carries a readable version past the cap, which an uncapped inflate would return) and the direct
 *    inflate_raw_capped checks; trusting the declared size alone fails it too.
 *  - no nested inflate: reading a nested entry fails the fat-jar read-count assertion.
 *  - verdict: returning supported for any non-complete stop fails the verdict table.
 *  - mount-table guard: walking when mount_table_unreadable is set fails the "no walk" case (its
 *    filesystem callbacks and its factory count every call).
 *  - heartbeat: deleting the storage_set loop, or any one key, fails the recorder assertions.
 *  - emission: setting `wrote` before the write fails the first-write-throws case; a catch-all that
 *    can throw fails the answer_internal_error cases.
 */
