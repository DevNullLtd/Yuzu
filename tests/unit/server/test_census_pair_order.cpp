/**
 * test_census_pair_order.cpp : UP-14 server PR B, commit B1: the census ORDER decision on the
 * agent's (boot_epoch, emit_seq) pair (#5690).
 *
 * Needs a Postgres database (YUZU_TEST_POSTGRES_DSN); without one every case here SKIPS, so a run
 * with no DSN proves nothing.
 *
 * What this file pins. PR A stored the pair on the event and on the census row and counted it per
 * agent, but the census row is still decided by the v4 key rule: the agent step computes a pair
 * mode and the census statement does not read it. These cases state the verdicts the pair
 * comparator must give. Each is written to FAIL against that tree for a stated reason (the census
 * row holds the verdict the key rule chooses, where the pair says otherwise) and to pass once the
 * comparator is in. A case that already passes today lives in the "already holds" group at the end
 * and says so in its name: it keeps a property the comparator must not lose.
 *
 * How to read an expectation. A schedule step is one delivery to one agent ("a"). `at` is the
 * receipt time and `ts` the agent's stamp, both in whole seconds of a made-up timeline, `epoch` and
 * `seq` are the pair (0/0 = an unpaired event), and `want` is the census row of the step's rule
 * after the step: "<verdict initial> <F when order_uncertain> <epoch>/<seq>" ("-/-" = an unpaired
 * verdict, "absent" = no row). Time passes by shifting every stored database-clock column back by
 * the elapsed seconds (the pair clock and the census marks), which is exactly what the clock reads
 * as later. `age_clock()` instead ages ONLY the agent's pair clock by two hours, as the plan's hold
 * cases do (SQL UPDATE of guardian_agent_order.epoch_recv_ns), leaving the census marks fresh. The
 * expected rows were produced by an executable model of the regime machine (the delivery plan's
 * prototype) and spot-checked against the design's cell tables, so they are the model's verdicts
 * and not yet the SQL's; the two `model seed` cases replay schedules generated by that model.
 */

