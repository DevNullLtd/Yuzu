// "<verdict initial> <F | -> <epoch>/<seq>" of the census row, "absent" with no row. The
// initials are compliant, drifted, errored: unique, so one letter names a verdict.
std::string verdict(const std::string& dsn, const std::string& agent, const std::string& rule) {
    const std::string v = query_scalar(
        dsn, std::string("SELECT upper(left(state, 1)) || ' ' || CASE WHEN order_uncertain THEN "
                         "'F' ELSE '-' END || ' ' || COALESCE(boot_epoch::text, '-') || '/' || "
                         "COALESCE(emit_seq::text, '-') FROM ") +
                 kSchema + ".guardian_agent_rule_status WHERE agent_id = '" + agent +
                 "' AND rule_id = '" + rule + "'");
    return v.empty() ? "absent" : v;
}

