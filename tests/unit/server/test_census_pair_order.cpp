// Number of backends in this database that wait on a lock.
int lock_waiters(const std::string& dsn) {
    return std::stoi(query_scalar(
        dsn, "SELECT count(*) FROM pg_stat_activity WHERE datname = current_database() AND "
             "wait_event_type = 'Lock'"));
}

// Poll until `n` backends wait on a lock, or `done` reports the thread under observation has
// finished (then nothing will ever wait). Observes a real park; a fixed sleep cannot.
bool wait_parked_or_done(const std::string& dsn, int n, const std::atomic<bool>& done) {
    const auto deadline = std::chrono::steady_clock::now() + std::chrono::seconds(10);
    while (std::chrono::steady_clock::now() < deadline) {
        if (done.load())
            return false;
        if (lock_waiters(dsn) >= n)
            return true;
        std::this_thread::sleep_for(std::chrono::milliseconds(25));
    }
    return false;
}

// ── The schedule driver ──────────────────────────────────────────────────────────────────────

enum class Kind { Send, SendFailing, Repair, Age };

struct Step {
    Kind kind{Kind::Send};
    std::int64_t at{0}; // receipt time, seconds of the timeline
    const char* rule{"r1"};
    char st{'C'};          // C compliant, D drifted, E errored
    std::int64_t ts{0};    // agent stamp, seconds of the timeline
    std::int64_t epoch{0}; // the pair; 0/0 is an unpaired event
    std::int64_t seq{0};
    int ref{0};           // Repair: the 1-based number of the step whose event is redelivered
    const char* want{""}; // the step's rule row afterwards
    int pend{0};          // pending events afterwards, all rules
};

Step deliver(std::int64_t at, const char* rule, char st, std::int64_t ts, std::int64_t epoch,
             std::int64_t seq, const char* want, int pend) {
    return {Kind::Send, at, rule, st, ts, epoch, seq, 0, want, pend};
}
Step deliver_failing(std::int64_t at, const char* rule, char st, std::int64_t ts,
                     std::int64_t epoch, std::int64_t seq, const char* want, int pend) {
    return {Kind::SendFailing, at, rule, st, ts, epoch, seq, 0, want, pend};
}
Step redeliver(std::int64_t at, int ref, const char* want, int pend) {
    return {Kind::Repair, at, "", 'C', 0, 0, 0, ref, want, pend};
}
Step age_clock() {
    return {Kind::Age, 0, "", 'C', 0, 0, 0, 0, "", 0};
}

GuaranteedStateEventRow step_event(const Step& s, std::size_t index) {
    const char* type = s.st == 'C' ? kCompliant : s.st == 'D' ? kDrifted : kErrored;
    auto e = ev("e" + std::to_string(index), s.rule, "a", type, kBase + s.ts * kSec,
                kBase + s.at * kSec);
    return s.epoch != 0 ? with_pair(std::move(e), s.epoch, s.seq) : e;
}

// Runs a schedule against agent "a" and checks, after every step, the step's rule row and the
// pending count. A Repair step must also leave the order table byte-identical. `order` is the
// agent's order row at the end ("" = not checked). Setup facts REQUIRE; verdicts CHECK, so one
// wrong verdict does not hide the next.
void run_schedule(GuaranteedStateStore& store, const std::string& dsn,
                  const std::vector<Step>& steps, const std::string& order) {
    std::vector<GuaranteedStateEventRow> events(steps.size() + 1);
    std::optional<FailSwitch> fail;
    std::int64_t last_at = -1;
    for (std::size_t i = 1; i <= steps.size(); ++i) {
        const Step& s = steps[i - 1];
        CAPTURE(i, s.at, s.rule, s.st, s.epoch, s.seq, s.want);
        if (s.kind == Kind::Age) {
            age_pair_clock(dsn, "a");
            continue;
        }
        if (last_at >= 0 && s.at > last_at)
            pass_time(dsn, (s.at - last_at) * kSec);
        last_at = s.at;
        std::string rule;
        if (s.kind == Kind::Repair) {
            const std::string before = order_snapshot(dsn);
            const auto& e = events[static_cast<std::size_t>(s.ref)];
            rule = e.rule_id;
            REQUIRE(store.insert_event_classified(e).outcome == EventInsertOutcome::Redelivered);
            CHECK(order_snapshot(dsn) == before); // a Repair never writes the order table
        } else {
            events[i] = step_event(s, i);
            rule = s.rule;
            if (s.kind == Kind::SendFailing) {
                if (!fail)
                    fail.emplace(dsn);
                fail->on();
            }
            const auto r = store.insert_event_classified(events[i]);
            if (fail && s.kind == Kind::SendFailing)
                fail->off();
            REQUIRE(r.outcome == EventInsertOutcome::Inserted);
        }
        CHECK(verdict(dsn, "a", rule) == s.want);
        CHECK(pending_count(dsn) == std::to_string(s.pend));
    }
    if (!order.empty())
        CHECK(order_text(dsn, "a") == order);
}

