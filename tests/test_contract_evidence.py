    def test_lease_release_failure_preserves_error_manifest_and_finalizes_history(self):
        def fail_unlock(fd):
            raise OSError("injected lease release failure")

        with patch.object(evidence, "_unlock_fd", fail_unlock):
            result, manifest = self.run_collector()
        self.assertEqual((result, manifest["status"]), (1, "ERROR"))
        self.assertIn("injected lease release failure", manifest["cleanup_error"])
        finish = self.history_calls[-1]
        self.assertEqual(finish[2], "run-finish")
        self.assertEqual(finish[finish.index("--status") + 1], "ABORTED")
        # Closing the descriptor ends the lease even when the explicit unlock failed.
        self.assert_lease_free()
        self.assertEqual(manifest["error_fields"], ["cleanup_error"])
        self.assertIn("contract-evidence: ERROR (no exception); recorded: cleanup_error;", self.stderr)
        self.assertNotIn("injected lease release failure", self.stderr)

    def test_successful_run_releases_the_lease_and_keeps_its_file(self):
        lease = self.build / ".contract-evidence.lease"
        self.assert_lease_free()
        inode = lease.stat().st_ino
        result, manifest = self.run_collector()
        self.assertEqual((result, manifest["status"]), (0, "PASS"), manifest)
        self.assertNotIn("error_fields", manifest)
        # Deleting the file would let a second collector lock a fresh inode while the
        # first still holds the old one: the lease is only exclusive if the file stays.
        self.assertEqual(lease.stat().st_ino, inode)
        self.assert_lease_free()
        self.assertEqual(self.stderr, "")

    @unittest.skipIf(os.name == "nt", "flock and O_NOFOLLOW are POSIX")
    def test_lock_faults_other_than_a_holder_propagate_and_close(self):
        import fcntl
        opened = []
        real_open = os.open

        def tracking_open(*args, **kwargs):
            fd = real_open(*args, **kwargs)
            opened.append(fd)
            return fd

        def no_locks(fd, operation):
            raise OSError(errno.ENOLCK, "No locks available")

        with patch.object(evidence.os, "open", tracking_open), patch.object(fcntl, "flock", no_locks):
            with self.assertRaises(OSError) as raised:
                evidence.acquire_lease(self.build)
        self.assertNotIsInstance(raised.exception, evidence.BuildDirectoryBusy)
        self.assertEqual(raised.exception.errno, errno.ENOLCK)
        self.assertEqual(len(opened), 1)
        with self.assertRaises(OSError):  # the failed attempt closed its descriptor
            os.fstat(opened[0])

    def test_windows_lock_errors_map_only_a_held_region_to_busy(self):
        # Exercise the msvcrt branch on every OS with a fake module: only a held region
        # (EACCES, or LK_LOCK's EDEADLOCK) is BuildDirectoryBusy; any other fault is itself.
        import types
        for code, busy in ((errno.EACCES, True), (getattr(errno, "EDEADLOCK", errno.EDEADLK), True),
                           (errno.ENOLCK, False), (errno.EBADF, False)):
            with self.subTest(errno=errno.errorcode.get(code, code)):
                calls = []

                def locking(fd, mode, length, code=code):
                    calls.append(mode)
                    raise OSError(code, os.strerror(code))

                fake = types.SimpleNamespace(LK_NBLCK=2, LK_UNLCK=0, locking=locking)
                fd = os.open(self.build / "probe", os.O_RDWR | os.O_CREAT, 0o600)
                try:
                    with patch.dict(sys.modules, {"msvcrt": fake}), patch.object(evidence.os, "name", "nt"):
                        with self.assertRaises((OSError, evidence.BuildDirectoryBusy)) as raised:
                            evidence._lock_fd(fd)
                finally:
                    os.close(fd)
                self.assertEqual(isinstance(raised.exception, evidence.BuildDirectoryBusy), busy)
                if not busy:
                    self.assertEqual(raised.exception.errno, code)
                self.assertEqual(calls, [fake.LK_NBLCK])

