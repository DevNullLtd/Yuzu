def contract():
    return {
        "id": "example.atomic", "meson_test": "contract.example.atomic",
        "kind": "catch2", "selector": "[example_atomic]", "case_name": "atomic replacement",
        "expected_cases": 1, "build_targets": ["case-binary"], "requires_env": [],
        "authority": {"kind": "accepted_adr", "path": "decision.md", "section": "Atomicity"},
        "obligation": "Failed replacement preserves the previous value.",
        "oracle": "Independent durable read observes the previous value.",
        "defects": ["Delete before committing the replacement."],
        "limits": ["One replacement operation."], "inputs": ["owner.cpp"],
    }


def native_report():
    # Independent native-shaped input, not generated by the adapter under test.
    return ET.fromstring('''<Catch2TestRun filters="[example_atomic]" rng-seed="123">
      <TestCase name="atomic replacement">
        <Expression success="true" type="REQUIRE"><Original>value == old</Original></Expression>
        <OverallResult success="true" skips="0"/>
      </TestCase>
      <OverallResults successes="1" failures="0" expectedFailures="0" skips="0"/>
      <OverallResultsCases successes="1" failures="0" expectedFailures="0" skips="0"/>
    </Catch2TestRun>''')


class RegistryTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="yuzu_test_contract_registry_")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        (self.root / "decision.md").write_text("# Decision\n- **Status:** Accepted\n## Atomicity\n")
        (self.root / "owner.cpp").write_text("// owner implementation\n")
        self.registry = self.root / "registry.json"

    def load(self, rows):
        self.registry.write_text(json.dumps({"schema_version": 1, "contracts": rows}))
        return evidence.load_registry(self.registry, self.root)

    def test_real_authority_and_exact_selection_are_accepted(self):
        self.assertEqual([r["id"] for r in self.load([contract()])], ["example.atomic"])

    def test_duplicate_identity_is_rejected(self):
        with self.assertRaises(ValueError):
            self.load([contract(), contract()])

    def test_unaccepted_adr_is_rejected(self):
        (self.root / "decision.md").write_text("# Decision\n- **Status:** Proposed\n## Atomicity\n")
        with self.assertRaises(ValueError):
            self.load([contract()])

    def test_missing_authority_or_section_is_rejected(self):
        for change in ("absent", "missing_file", "missing_section", "empty_section"):
            with self.subTest(change=change):
                row = contract()
                if change == "absent":
                    del row["authority"]
                elif change == "missing_file":
                    row["authority"]["path"] = "does-not-exist.md"
                else:
                    row["authority"]["section"] = "" if change == "empty_section" else "Absent section"
                with self.assertRaises((ValueError, KeyError, TypeError)):
                    self.load([row])

    def test_authority_cannot_escape_repository(self):
        row = contract()
        row["authority"]["path"] = str(MODULE_PATH)
        with self.assertRaises(ValueError):
            self.load([row])

    def test_no_contracts_cannot_be_validated_as_a_plan(self):
        with self.assertRaises(ValueError):
            self.load([])


