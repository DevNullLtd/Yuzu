    def check_nested_cancellation(self, mode):
        # Actual Meson + actual case adapter: both create sessions of their own.
        # A direct-child-only timeout test cannot expose these orphaned groups.
        meson = shutil.which("meson")
        self.assertIsNotNone(meson, "Meson is required for the runner ownership regression")
        with tempfile.TemporaryDirectory(prefix="yuzu_test_contract_nested_") as temporary:
            root = Path(temporary).resolve()
            native = root / "native.py"
            identity = root / "identity.json"
            native.write_text(
                "import json,os,signal,time\nfrom pathlib import Path\n"
                "signal.signal(signal.SIGTERM,signal.SIG_IGN)\n"
                f"p=Path({str(identity)!r}); t=p.with_suffix('.tmp')\n"
                "t.write_text(json.dumps(dict(native=os.getpid(),adapter=os.getppid())));t.replace(p)\n"
                "time.sleep(60)\n")
            binary = root / "native"
            binary.write_text(f"#!/bin/sh\nexec {shlex.quote(sys.executable)} {shlex.quote(str(native))}\n")
            binary.chmod(0o700)
            def quoted(value):
                return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"
            args = [str(MODULE_PATH), "case", "--id", "plugin.loader.reserved-name.reject", "--binary", str(binary)]
            (root / "meson.build").write_text(
                "project('contract-process-ownership')\n"
                f"py=find_program({quoted(sys.executable)})\n"
                f"test('owned-case',py,args:[{','.join(quoted(arg) for arg in args)}],timeout:120)\n")
            env = {key: os.environ[key] for key in ("PATH", "HOME", "TMPDIR", "LANG") if key in os.environ}
            setup = subprocess.run([meson, "setup", str(root / "build"), str(root)],
                                   env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=15)
            self.assertEqual(setup.returncode, 0, setup.stdout.decode(errors="replace"))
            command = [meson, "test", "-C", str(root / "build"), "--no-rebuild"]
            timeout = 5 if mode == "timeout" else 30
            driver = root / "driver.py"
            driver.write_text(
                "import importlib.util,json,os,subprocess\nfrom pathlib import Path\n"
                f"s=importlib.util.spec_from_file_location('collector',{str(MODULE_PATH)!r})\n"
                "m=importlib.util.module_from_spec(s);s.loader.exec_module(m)\n"
                "popen=m.subprocess.Popen\n"
                "def start(*a,**kw):\n p=popen(*a,**kw)\n"
                f" Path({str(root / 'meson.pid')!r}).write_text(str(p.pid))\n return p\n"
                "m.subprocess.Popen=start\ntry:\n"
                f" m.bounded({command!r},Path({str(root)!r}),os.environ.copy(),Path({str(root / 'outer.log')!r}),{timeout},cancel_grace=5)\n"
                "except (subprocess.TimeoutExpired,KeyboardInterrupt) as e:\n"
                f" Path({str(root / 'outcome')!r}).write_text(type(e).__name__)\n")
            child = subprocess.Popen([sys.executable, str(driver)], env=env,
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                     start_new_session=True)
            owned = {}
            try:
                deadline = time.monotonic() + 4
                while not identity.exists() and time.monotonic() < deadline:
                    time.sleep(0.02)
                self.assertTrue(identity.exists(), "native child must actually start")
                owned = json.loads(identity.read_text())
                self.assertEqual(os.getpgid(owned["native"]), owned["native"])
                self.assertEqual(os.getpgid(owned["adapter"]), owned["adapter"])
                if mode == "interrupt":
                    os.kill(child.pid, signal.SIGINT)
                self.assertEqual(child.wait(timeout=12), 0)
                expected = "TimeoutExpired" if mode == "timeout" else "KeyboardInterrupt"
                self.assertEqual((root / "outcome").read_text(), expected)
                for pid in owned.values():
                    with self.assertRaises(ProcessLookupError):
                        os.kill(pid, 0)
            finally:
                if identity.exists():
                    owned.update(json.loads(identity.read_text()))
                if (root / "meson.pid").exists():
                    owned["meson"] = int((root / "meson.pid").read_text())
                owned["driver"] = child.pid
                for pid in owned.values():
                    try:
                        if os.getpgid(pid) == pid:
                            os.killpg(pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
                child.wait(timeout=5)

    def test_closed_output_does_not_end_deadline_and_timed_out_child_is_reaped(self):
        with tempfile.TemporaryDirectory(prefix="yuzu_test_contract_child_") as temporary:
            root = Path(temporary)
            real_popen = subprocess.Popen
            children = []

            def start(*args, **kwargs):
                child = real_popen(*args, **kwargs)
                children.append(child)
                return child

            # No pipes remain open, but the process is still alive. EOF must
            # never be interpreted as completion, nor may timeout leak it.
            command = [sys.executable, "-c", "import os,time;os.close(1);os.close(2);time.sleep(60)"]
            started = time.monotonic()
            try:
                with patch.object(evidence.subprocess, "Popen", side_effect=start):
                    with self.assertRaises(subprocess.TimeoutExpired):
                        evidence.bounded(command, root, os.environ.copy(), root / "child.log", 0.15)
                self.assertLess(time.monotonic() - started, 12)
                # Windows cleanup also launches taskkill through Popen. Identify
                # the native child, then require every observed process (including
                # cleanup helpers) to have been reaped before bounded() returns.
                native = [child for child in children if child.args == command]
                self.assertEqual(len(native), 1)
                for child in children:
                    self.assertIsNotNone(child.returncode, child.args)
                    self.assertIsNotNone(child.poll(), child.args)
                    if os.name != "nt":
                        with self.assertRaises(ChildProcessError):
                            os.waitpid(child.pid, os.WNOHANG)
            finally:
                for child in children:
                    if child.poll() is None:
                        child.kill()
                        child.wait(timeout=5)


