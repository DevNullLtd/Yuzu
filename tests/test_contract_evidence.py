class ChildLifetimeTests(unittest.TestCase):
    @unittest.skipIf(os.name == "nt", "POSIX process groups")
    def test_gracefully_reaped_runner_is_not_signalled_again(self):
        with tempfile.TemporaryDirectory(prefix="yuzu_test_contract_reaped_") as temporary:
            root = Path(temporary)
            with patch.object(evidence.subprocess, "Popen") as start, \
                 patch.object(evidence.os, "killpg") as kill_group:
                child = start.return_value
                child.pid = 12345
                child.wait.side_effect = [subprocess.TimeoutExpired(['meson'], 1), 0, 0]
                child.poll.return_value = 0
                with self.assertRaises(subprocess.TimeoutExpired):
                    evidence.bounded(['meson'], root, {}, root/'child.log', 1, cancel_grace=5)
                kill_group.assert_called_once_with(child.pid, signal.SIGTERM)

    @unittest.skipIf(os.name == "nt", "POSIX signals; Windows uses taskkill /T")
    def test_repeated_signals_cannot_interrupt_owned_child_cleanup(self):
        with tempfile.TemporaryDirectory(prefix="yuzu_test_contract_signals_") as temporary:
            root = Path(temporary)
            real_popen, real_killpg = subprocess.Popen, os.killpg
            children = []

            def start(*args, **kwargs):
                child = real_popen(*args, **kwargs)
                children.append(child)
                return child

            def interrupted_kill(group, sig):
                # Real repeated signals at the exact cleanup boundary.
                os.kill(os.getpid(), signal.SIGINT)
                os.kill(os.getpid(), signal.SIGTERM)
                return real_killpg(group, sig)

            original_term = signal.signal(signal.SIGTERM, evidence.termination_interrupt)
            handlers = {sig: signal.getsignal(sig) for sig in (signal.SIGINT, signal.SIGTERM)}
            try:
                with patch.object(evidence.subprocess, "Popen", side_effect=start), \
                     patch.object(evidence.os, "killpg", side_effect=interrupted_kill):
                    with self.assertRaises(subprocess.TimeoutExpired):
                        evidence.bounded([sys.executable, "-c", "import time;time.sleep(60)"],
                                         root, os.environ.copy(), root / "child.log", 0.15)
                self.assertEqual({sig: signal.getsignal(sig) for sig in handlers}, handlers)
                self.assertIsNotNone(children[0].poll())
            finally:
                signal.signal(signal.SIGTERM, original_term)
                for child in children:
                    if child.poll() is None:
                        real_killpg(child.pid, signal.SIGKILL)
                    child.wait(timeout=5)

