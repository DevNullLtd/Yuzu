%% The nodes a case started, so end_per_testcase can stop them all (a crash
%% scenario replaces nodes, and end_per_testcase does not see the case's
%% Config). A plain unlinked process in the CT node owns the list.
tracker_start() ->
    case whereis(yuzu_gw_scale_peers) of
        undefined ->
            Pid = spawn(fun() -> tracker_loop([]) end),
            register(yuzu_gw_scale_peers, Pid),
            ok;
        _ -> ok
    end.

tracker_loop(Peers) ->
    receive
        {track, Role, Peer} -> tracker_loop([{Role, Peer} | Peers]);
        {take, From, Ref} -> From ! {Ref, Peers}, tracker_loop([])
    end.

track(Role, Peer) ->
    yuzu_gw_scale_peers ! {track, Role, Peer},
    ok.

stop_tracked() ->
    case whereis(yuzu_gw_scale_peers) of
        undefined -> ok;
        Pid ->
            Ref = make_ref(),
            Pid ! {take, self(), Ref},
            Peers = receive {Ref, P} -> P after 5000 -> [] end,
            Order = fun(gateway) -> 0; (upstream) -> 1; (loadgen) -> 2 end,
            Sorted = lists:sort(fun({A, _}, {B, _}) -> Order(A) =< Order(B) end, Peers),
            [?PEER:stop(P) || {_, P} <- Sorted],
            ok
    end.

