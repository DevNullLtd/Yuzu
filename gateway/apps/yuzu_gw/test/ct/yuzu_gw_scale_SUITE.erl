%% @doc N agents connect and register at a fixed rate.
ramp(Config) ->
    N = ?config(n, Config),
    Rate = env_int("YUZU_GW_SCALE_RAMP_RATE", 100),
    set_upstream(Config, #{register_latency_ms => latency()}),
    T0 = mark(Config),
    ok = load_call(Config, spawn_agents, [#{from => 1, count => N, mode => {ramp, Rate}}]),
    Reg = await_registered(Config, N, T0),
    Settle = settle(Config),
    R = registration_report(Config, T0, Reg),
    finish(ramp, Config, R#{rate_per_s => Rate, settle => Settle}).

%% @doc N agents connect and register at once (a thundering herd).
storm(Config) ->
    N = ?config(n, Config),
    set_upstream(Config, #{register_latency_ms => latency()}),
    T0 = mark(Config),
    ok = load_call(Config, spawn_agents, [#{from => 1, count => N, mode => storm}]),
    Reg = await_registered(Config, N, T0),
    Settle = settle(Config),
    R = registration_report(Config, T0, Reg),
    finish(storm, Config, R#{settle => Settle}).

%% @doc The server is killed while N agents are registered and a fresh one is
%% started on the same port after the outage; FlapPct of the agents drop their
%% connection 500 ms into the outage (their DISCONNECTED notices must be held
%% and delivered, and they come back by the agent's retry rule).
server_crash(Config) ->
    N = ?config(n, Config),
    Pre = setup_registered(Config),
    PreTruth = truth(Config),
    Outage = env_int("YUZU_GW_SCALE_OUTAGE_MS", 5000),
    FlapN = max(1, N * env_int("YUZU_GW_SCALE_FLAP_PCT", 10) div 100),
    {Flapped, Kept} = lists:split(FlapN, lists:sort(PreTruth)),
    T0 = mark(Config),
    ok = ?PEER:kill(?config(up, Config)),
    timer:sleep(500),
    ok = load_call(Config, disconnect, [[Id || {Id, _, _} <- Flapped]]),
    timer:sleep(max(0, Outage - 500)),
    Up2 = start_upstream_node(log(?config(log_dir, Config), upstream,
                                  ?config(tag, Config) ++ "-2")),
    {ok, _} = ?PEER:call(Up2, ?UP, start, [#{port => ?config(up_port, Config),
                                            register_latency_ms => latency()}]),
    Config2 = lists:keystore(up, 1, Config, {up, Up2}),
    T1 = erlang:system_time(millisecond),
    KeptSessions = [{Id, S} || {Id, S, _} <- Kept],
    FlapOld = [S || {_, S, _} <- Flapped],
    %% Two waits, each ended early by a stall (no progress for a while), so a
    %% notice that is lost for good does not hold the run until the cap: the
    %% replay and the flapped agents' return (the agents' backoff reaches 16 s
    %% between tries, so 60 s without progress is a stall), then the held
    %% DISCONNECTED notices (delivered within one drain once the breaker closes).
    Progress = fun() ->
                       #{replayed := Rp, live := L, flap_disc := FD} = P =
                           crash_progress(Config2, KeptSessions, FlapOld, N),
                       {Rp =:= length(KeptSessions) andalso L =:= N, P, {Rp, L, FD}}
               end,
    Poll = max(500, N div 5),
    {ReplayedAll, _} = wait_progress(Progress, budget(N) * 3, 60000, Poll),
    {Reached, _} = wait_progress(fun() ->
                                         #{done := D, flap_disc := FD} = P =
                                             crash_progress(Config2, KeptSessions, FlapOld, N),
                                         {D, P, FD}
                                 end, 60000, 10000, Poll),
    Settle = settle(Config2),
    #{replayed := Replayed, replay_last_ms := LastReplay, flap_disc := FlapDisc} =
        crash_progress(Config2, KeptSessions, FlapOld, N),
    Up = up_call(Config2, stats, []),
    Conv = convergence(Config2),
    R0 = registration_report(Config2, T1, #{}, attempting),
    R = R0#{setup => Pre,
            outage_ms => Outage,
            flapped => FlapN,
            replay => #{expected => length(KeptSessions), replayed => Replayed,
                        complete => Replayed =:= length(KeptSessions),
                        time_to_full_replay_ms => case Replayed =:= length(KeptSessions) of
                                                      true -> LastReplay - T1;
                                                      false -> null
                                                  end,
                        replay_and_agents_back => ReplayedAll,
                        all_converged => Reached,
                        peak_inflight => maps:get(replay_peak_inflight, Up),
                        replay_rpcs => maps:get(replay_rpcs, Up)},
            disconnected_expected => length(FlapOld),
            disconnected_received => FlapDisc,
            disconnected_lost => length(FlapOld) - FlapDisc,
            convergence => Conv, settle => Settle,
            elapsed_since_kill_ms => erlang:system_time(millisecond) - T0},
    finish(server_crash, Config2, R).

%% @doc The gateway node is killed while N agents are registered; a new
%% gateway starts on the same ports and every agent comes back.
gateway_crash(Config) ->
    N = ?config(n, Config),
    Pre = setup_registered(Config),
    Old = maps:from_list([{Id, S} || {Id, S, _} <- truth(Config)]),
    PreProbe = probe_report(Config),
    set_upstream(Config, #{register_latency_ms => latency()}),
    #{peer := OldGw} = Gw = ?config(gw, Config),
    T0 = erlang:system_time(millisecond),
    ok = ?PEER:kill(OldGw),
    ?PEER:stop(OldGw),
    Gw2 = start_gateway(#{log => log(?config(log_dir, Config), gateway, ?config(tag, Config) ++ "-2"),
                          fds => ?config(fds, Config), upstream_port => ?config(up_port, Config),
                          n => N, agent_port => maps:get(agent_port, Gw),
                          agent6_port => maps:get(agent6_port, Gw),
                          mgmt_port => maps:get(mgmt_port, Gw)}),
    TUp = erlang:system_time(millisecond),
    Config2 = lists:keystore(gw, 1, Config, {gw, Gw2}),
    Back = fun() ->
                   Now = [Id || {Id, S, _} <- truth(Config2), maps:get(Id, Old, S) =/= S],
                   case length(Now) of N -> {true, N}; K -> {false, K} end
           end,
    {Reached, Count} = wait_until(Back, budget(N) * 3, 500),
    TBack = erlang:system_time(millisecond),
    Settle = settle(Config2),
    Attempts = load_call(Config2, attempts, []),
    After = [A || {_, _, Start, _, _} = A <- Attempts, Start >= TUp],
    Failures = [A || {_, _, _, _, Outcome} = A <- After, Outcome =/= ok],
    OldSessions = maps:values(Old),
    Notices = up_call(Config2, notices, []),
    OldDisc = length([1 || {_, S, disconnected, _} <- Notices,
                           lists:member(S, OldSessions)]),
    R0 = registration_report(Config2, TUp, #{}, attempting),
    R = R0#{setup => Pre,
            pre_kill_probe => PreProbe,
            gateway_restart_ms => TUp - T0,
            reregistered => Count, all_reregistered => Reached,
            time_to_all_reregistered_ms => case Reached of true -> TBack - T0; false -> null end,
            register_failures_after_restart => length(Failures),
            register_failure_reasons_after_restart => reasons(Failures),
            %% A kill -9 gives no last gasp: the server only learns the old
            %% sessions are gone by its own expiry. Reported, not checked.
            ghost_sessions_old => length(OldSessions) - OldDisc,
            convergence => convergence(Config2), settle => Settle},
    finish(gateway_crash, Config2, R).

%% @doc A planned stop of the gateway application with N agents registered:
%% the server should receive a DISCONNECTED notice for every session.
planned_stop(Config) ->
    Pre = setup_registered(Config),
    Live = truth(Config),
    Sessions = [S || {_, S, _} <- Live],
    ok = load_call(Config, set_config, [#{reconnect => false}]),
    PreProbe = probe_report(Config),
    _ = mark(Config),
    #{peer := GwPeer} = ?config(gw, Config),
    T0 = erlang:system_time(millisecond),
    StopResult = ?PEER:call(GwPeer, application, stop, [yuzu_gw], 600000),
    StopMs = erlang:system_time(millisecond) - T0,
    %% The probe is not part of the application: it sampled through the stop.
    StopProbe = probe_report(Config),
    StopSched = probe_call(Config, sched_report, []),
    %% Anything still on its way when stop returned has had 2 s to land.
    timer:sleep(2000),
    Notices = up_call(Config, notices, []),
    Set = sets:from_list(Sessions, [{version, 2}]),
    Received = sets:size(sets:from_list([S || {_, S, disconnected, _} <- Notices,
                                              sets:is_element(S, Set)], [{version, 2}])),
    R = #{setup => Pre,
          stop_result => iolist_to_binary(io_lib:format("~0p", [StopResult])),
          stop_ms => StopMs,
          sessions => length(Sessions),
          disconnected_received => Received,
          disconnected_lost => length(Sessions) - Received,
          gateway => #{probe_before_stop => PreProbe, probe_during_stop => StopProbe,
                       scheduler_during_stop => StopSched}},
    finish(planned_stop, Config, R).

%% @doc The server fans one command out to the N agents over one management
%% connection (one SendCommand per agent); agents answer after 0-10 s.
fanout(Config) ->
    N = ?config(n, Config),
    Pre = setup_registered(Config),
    Live = truth(Config),
    Ids = [Id || {Id, _, _} <- Live],
    Delay = range_env("YUZU_GW_SCALE_FANOUT_DELAY_MS", {0, 10000}),
    Window = env_int("YUZU_GW_SCALE_FANOUT_WINDOW", 1024),
    ok = load_call(Config, set_config, [#{reply_delay_ms => Delay}]),
    #{disconnects := Disc0} = load_call(Config, status, []),
    probe_call(Config, reset_hwm, []),
    probe_call(Config, sched_mark, []),
    Gw = ?config(gw, Config),
    Budget = budget(N) + element(2, Delay),
    Fan = ?PEER:call(?config(load, Config), ?FLEET, fanout,
                     [#{target => {?LOOPBACK, maps:get(mgmt_port, Gw)}, ids => Ids,
                        window => Window, budget_ms => Budget, timeout_s => 300}],
                     Budget + 120000),
    #{disconnects := Disc1} = load_call(Config, status, []),
    Lat = maps:get(latencies_ms, Fan),
    R = #{setup => Pre,
          targets => length(Ids), window => Window,
          reply_delay_ms => tuple_to_list(Delay),
          fanout => maps:without([latencies_ms], Fan),
          latency_ms => stats(Lat),
          agent_disconnects_during => Disc1 - Disc0,
          gateway => gateway_report(Config)},
    finish(fanout, Config, R).

%%%===================================================================
%%% Invariants (no timing in any of them)
