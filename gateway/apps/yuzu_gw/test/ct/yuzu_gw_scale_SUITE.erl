%%%-------------------------------------------------------------------
%%% @doc Gateway scale suite: N simulated agents against the REAL gateway
%%% listeners over real HTTP/2, with the C++ server replaced by a fake that
%%% speaks the GatewayUpstream service on a real listener (so the gateway's own
%%% upstream client, circuit breaker and replay are exercised, not mocked).
%%%
%%% Shape (amoc / Tsung practice: the load generator is not the system under
%%% test): every scenario starts three peer nodes, see yuzu_gw_scale_peer:
%%%   gateway   yuzu_gw, listeners as in sys.config.prod (plaintext), OS ports;
%%%   upstream  yuzu_gw_scale_upstream, the fake server;
%%%   loadgen   yuzu_gw_scale_fleet, the agents and the management client.
%%% Each agent registers with a RegisterRequest shaped like a real agent's: 69
%%% plugins (yuzu_gw_scale_SUITE_data/register_plugins.eterm, regenerated by
%%% scripts/test/gen-gateway-scale-register-fixture.py).
%%%
%%% Scenarios (one test case each):
%%%   ramp           N agents connect and register at a fixed rate
%%%   storm          N agents at once; the server answers Register in 20-50 ms
%%%   server_crash   N registered; the fake server is killed (kill -9) and a
%%%                  fresh one started on the same port; 10% of the agents drop
%%%                  their connection during the outage. Measures time to full
%%%                  replay and notices lost
%%%   gateway_crash  N registered; the gateway node is killed (kill -9) and a
%%%                  new one started on the same ports; every agent reconnects
%%%                  by the agent's own retry rule (2 s, then 4, 8, ...)
%%%   planned_stop   N registered; application:stop(yuzu_gw). Counts the
%%%                  DISCONNECTED notices the server received
%%%   fanout         N registered; the server sends one command to each agent
%%%                  (one SendCommand per agent, one management connection, at
%%%                  most 1024 open); agents answer after 0-10 s
%%%
%%% Each scenario MEASURES and REPORTS (never fails on a timing): registration
%%% counts and latency percentiles, replay time, notices lost, gateway memory
%%% per connection, the mailbox high-water mark of each named singleton, and
%%% scheduler utilisation. Results go to a JSON file per scenario and one per
%%% run (in the CT log dir, or YUZU_GW_SCALE_RESULTS_DIR), and to SCALE_METRIC
%%% lines (scripts/test/perf-gate.sh records them).
%%%
%%% It CHECKS INVARIANTS (no timing in any of them; see invariants/2 for each):
%%% zero first-attempt Register failures, more than one Register in flight at
%%% the server at once, no session created at the server for a Register attempt
%%% that failed, a complete replay with more than one in flight, zero lost
%%% DISCONNECTED notices (planned stop and outage), every live session known to
%%% the server, every command answered, the management connection kept, and the
%%% singleton mailboxes back to 0. Several FAIL on the gateway as of 29a8e655b
%%% (the serial upstream lane, the 20 ms replay drip, the planned-stop drain
%%% that runs after the tree is gone). In the default group `report' a violated
%%% invariant is recorded (JSON, a ct:pal line, the test case comment) and the
%%% case passes; in the group `gate' it fails the case. YUZU_GW_SCALE_GATE=1
%%% selects `gate'; it is meant to be switched on in CI once the fixes merge.
%%%
%%% Sizes: YUZU_GW_SCALE_AGENTS (default 500, the CI size). 5000 and 25000 are
%%% on-demand sizes; see docs/testing/gateway-scale-tests.md (file descriptor
%%% limits, macOS ephemeral ports, run time).
%%%
%%% Other knobs (all optional): YUZU_GW_SCALE_RAMP_RATE (agents/s, 100),
%%% YUZU_GW_SCALE_LATENCY_MS ("20-50", the server's Register latency),
%%% YUZU_GW_SCALE_OUTAGE_MS (5000), YUZU_GW_SCALE_FLAP_PCT (10),
%%% YUZU_GW_SCALE_FANOUT_DELAY_MS ("0-10000"), YUZU_GW_SCALE_FANOUT_WINDOW (1024),
%%% YUZU_GW_SCALE_OUTPUT_BYTES (2048), YUZU_GW_SCALE_HB_MS (30000),
%%% YUZU_GW_SCALE_BUDGET_MS (60000 + 10 ms per agent), YUZU_GW_SCALE_RESULTS_DIR.
%%%
%%% Run:
%%%   rebar3 ct --dir apps/yuzu_gw/test/ct --suite yuzu_gw_scale_SUITE
%%%   YUZU_GW_SCALE_AGENTS=5000 rebar3 ct --dir apps/yuzu_gw/test/ct --suite yuzu_gw_scale_SUITE --case storm
%%% @end
%%%-------------------------------------------------------------------
-module(yuzu_gw_scale_SUITE).

-include_lib("common_test/include/ct.hrl").

-compile([export_all, nowarn_export_all]).

-define(PEER, yuzu_gw_scale_peer).
-define(FLEET, yuzu_gw_scale_fleet).
-define(UP, yuzu_gw_scale_upstream).
-define(PROBE, yuzu_gw_scale_probe).
-define(LOOPBACK, {127, 0, 0, 1}).
-define(LOOPBACK6, {0, 0, 0, 0, 0, 0, 0, 1}).
%% Above this many agents half of them use an IPv6 loopback listener: macOS has
%% one IPv4 loopback address and about 16,000 ephemeral ports per address.
-define(DUAL_STACK_ABOVE, 14000).

%%%===================================================================
%%% CT callbacks
%%%===================================================================

cases() -> [ramp, storm, server_crash, gateway_crash, planned_stop, fanout].

all() ->
    case os:getenv("YUZU_GW_SCALE_GATE") of
        "1" -> [{group, gate}];
        _ -> [{group, report}]
    end.

groups() ->
    %% Not `sequence': every case starts its own nodes, so one failed
    %% invariant must not skip the cases after it.
    [{report, [], cases()},
     {gate, [], cases()}].

suite() ->
    [{timetrap, {minutes, 120}}].

init_per_suite(Config) ->
    case {os:type(), os:getenv("YUZU_GW_SCALE_WINDOWS")} of
        {{win32, _}, V} when V =/= "1" ->
            %% Not yet run on Windows (peer nodes over standard_io, the kill
            %% path, port ranges); YUZU_GW_SCALE_WINDOWS=1 runs it anyway.
            {skip, "gateway scale suite not validated on Windows; set YUZU_GW_SCALE_WINDOWS=1"};
        _ ->
            init_per_suite_checked(Config)
    end.

init_per_suite_checked(Config) ->
    tracker_start(),
    {ok, [{plugins, Plugins}]} =
        file:consult(filename:join(?config(data_dir, Config), "register_plugins.eterm")),
    N = env_int("YUZU_GW_SCALE_AGENTS", 500),
    Run = run_tag(),
    ResultsDir = case os:getenv("YUZU_GW_SCALE_RESULTS_DIR") of
                     false -> ?config(priv_dir, Config);
                     D -> D
                 end,
    ok = filelib:ensure_path(ResultsDir),
    ct:pal("Gateway scale suite: N=~b, run ~s, ~b plugins per RegisterRequest, results in ~s",
           [N, Run, length(Plugins), ResultsDir]),
    [{n, N}, {run, Run}, {plugins, Plugins}, {results_dir, ResultsDir} | Config].

end_per_suite(_Config) ->
    stop_tracked(),
    case whereis(yuzu_gw_scale_peers) of
        undefined -> ok;
        Pid -> exit(Pid, kill)
    end,
    ok.

init_per_group(Group, Config) ->
    [{mode, Group}, {started_at, erlang:system_time(millisecond)} | Config].

end_per_group(_Group, Config) ->
    %% One file for the run: every scenario's result, in run order.
    Dir = ?config(results_dir, Config),
    Run = ?config(run, Config),
    Files = lists:sort(filelib:wildcard(filename:join(Dir, "yuzu_gw_scale-" ++ Run ++ "-*.json"))),
    Results = [json:decode(element(2, file:read_file(F))) || F <- Files],
    Out = filename:join(Dir, "yuzu_gw_scale-" ++ Run ++ ".json"),
    ok = file:write_file(Out, json:encode(#{run => list_to_binary(Run),
                                            agents => ?config(n, Config),
                                            mode => mode(Config),
                                            host => host_facts(),
                                            scenarios => Results})),
    ct:pal("Gateway scale run summary: ~s", [Out]),
    ok.

init_per_testcase(Case, Config) ->
    N = ?config(n, Config),
    Tag = ?config(run, Config) ++ "-" ++ atom_to_list(Case),
    LogDir = ?config(priv_dir, Config),
    Fds = 2 * N + 4096,
    Up = start_upstream_node(log(LogDir, upstream, Tag)),
    {ok, UpPort} = ?PEER:call(Up, ?UP, start, [#{port => 0}]),
    Gw = start_gateway(#{log => log(LogDir, gateway, Tag), fds => Fds, upstream_port => UpPort,
                         n => N, agent_port => 0, agent6_port => 0, mgmt_port => 0}),
    {ok, Load} = ?PEER:start(loadgen, #{fds => Fds, log => log(LogDir, loadgen, Tag),
                                        args => ["+sbwt", "none"]}),
    track(loadgen, Load),
    ok = ?PEER:call(Load, ?FLEET, start,
                    [#{targets => targets(Gw), prefix => list_to_binary("a" ++ short_tag()),
                       plugins => ?config(plugins, Config),
                       hb_interval_ms => env_int("YUZU_GW_SCALE_HB_MS", 30000),
                       output_bytes => env_int("YUZU_GW_SCALE_OUTPUT_BYTES", 2048)}]),
    ct:pal("~p: upstream :~b, gateway agent ~p mgmt :~b, fds gateway ~p loadgen ~p",
           [Case, UpPort, targets(Gw), maps:get(mgmt_port, Gw), ?PEER:fds(maps:get(peer, Gw)),
            ?PEER:fds(Load)]),
    [{up, Up}, {up_port, UpPort}, {gw, Gw}, {load, Load}, {tag, Tag}, {log_dir, LogDir},
     {fds, Fds} | Config].

end_per_testcase(_Case, _Config) ->
    %% Every node this case started, including the ones a crash scenario
    %% started in place of the killed ones (the case's own Config is not passed
    %% here). Gateways first: their sockets close with the agents still up, so
    %% no TIME_WAIT is left on the load generator's ephemeral ports (the agents'
    %% own sockets reset on close, linger 0).
    stop_tracked(),
    ok.

