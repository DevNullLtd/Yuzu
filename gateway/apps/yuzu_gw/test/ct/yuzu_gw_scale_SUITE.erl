%% Poll Fun (-> {Done, Value}) every IntervalMs until Done or TimeoutMs passed.
%% Returns {Done, LastValue}.
wait_until(Fun, TimeoutMs, IntervalMs) ->
    wait_until(Fun, erlang:monotonic_time(millisecond) + TimeoutMs, IntervalMs, undefined).

wait_until(Fun, Deadline, IntervalMs, _Last) ->
    case Fun() of
        {true, V} -> {true, V};
        {false, V} ->
            case erlang:monotonic_time(millisecond) >= Deadline of
                true -> {false, V};
                false -> timer:sleep(IntervalMs), wait_until(Fun, Deadline, IntervalMs, V)
            end
    end.

%% Poll Fun (-> {Done, Value, Progress}) every IntervalMs until Done, until
%% CapMs passed, or until Progress has not changed for StallMs. Returns
%% {Done, LastValue}.
wait_progress(Fun, CapMs, StallMs, IntervalMs) ->
    Now = erlang:monotonic_time(millisecond),
    wait_progress(Fun, Now + CapMs, StallMs, IntervalMs, {make_ref(), Now}).

wait_progress(Fun, Deadline, StallMs, IntervalMs, {LastP, Since}) ->
    {Done, V, P} = Fun(),
    Now = erlang:monotonic_time(millisecond),
    Since1 = case P =:= LastP of true -> Since; false -> Now end,
    if
        Done -> {true, V};
        Now >= Deadline -> {false, V};
        Now - Since1 >= StallMs -> {false, V};
        true -> timer:sleep(IntervalMs),
                wait_progress(Fun, Deadline, StallMs, IntervalMs, {P, Since1})
    end.

