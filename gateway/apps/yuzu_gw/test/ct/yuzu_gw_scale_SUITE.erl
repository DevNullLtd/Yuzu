flatten(Prefix, M) when is_map(M) ->
    lists:append([flatten(Prefix ++ "_" ++ key(K), V) || {K, V} <- lists:sort(maps:to_list(M)),
                                                          K =/= invariants]);
flatten(Prefix, V) when is_integer(V); is_float(V) -> [{Prefix, V}];
flatten(Prefix, true) -> [{Prefix, 1}];
flatten(Prefix, false) -> [{Prefix, 0}];
flatten(_Prefix, _) -> [].

key(K) when is_atom(K) -> atom_to_list(K);
key(K) when is_binary(K) -> re:replace(binary_to_list(K), "[^A-Za-z0-9_]", "_", [global, {return, list}]);
key(K) -> lists:flatten(io_lib:format("~p", [K])).

num(V) when is_integer(V) -> integer_to_list(V);
num(V) when is_float(V) -> float_to_list(V, [{decimals, 4}, compact]).

jsonable(M) when is_map(M) ->
    maps:from_list([{jkey(K), jsonable(V)} || {K, V} <- maps:to_list(M)]);
%% Every string in a result is a binary already; a list is always an array.
jsonable(L) when is_list(L) -> [jsonable(E) || E <- L];
jsonable(T) when is_tuple(T) -> jsonable(tuple_to_list(T));
jsonable(V) when is_atom(V), V =/= true, V =/= false, V =/= null -> atom_to_binary(V);
jsonable(V) when is_pid(V); is_reference(V); is_port(V); is_function(V) ->
    iolist_to_binary(io_lib:format("~p", [V]));
jsonable(V) -> V.

jkey(K) when is_atom(K) -> K;
jkey(K) when is_binary(K) -> K;
jkey(K) -> iolist_to_binary(io_lib:format("~0p", [K])).

stats([]) -> #{n => 0};
stats(L) ->
    S = lists:sort(L),
    N = length(S),
    #{n => N, min => hd(S), max => lists:last(S), mean => lists:sum(S) / N,
      p50 => pct(S, N, 50), p95 => pct(S, N, 95), p99 => pct(S, N, 99)}.

pct(S, N, P) -> lists:nth(max(1, min(N, round(P / 100 * N))), S).

reasons(Attempts) ->
    lists:foldl(fun({_, _, _, _, O}, Acc) ->
                        K = iolist_to_binary(io_lib:format("~0p", [O])),
                        maps:update_with(K, fun(X) -> X + 1 end, 1, Acc)
                end, #{}, Attempts).

