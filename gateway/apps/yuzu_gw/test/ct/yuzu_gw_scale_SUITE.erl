invariants(ramp, R) -> registration_invariants(R);
invariants(storm, R) -> registration_invariants(R);
invariants(server_crash, R) ->
    #{replay := Replay, disconnected_lost := Lost, convergence := Conv} = R,
    [inv(replay_complete, maps:get(complete, Replay),
         "every session the gateway held was replayed to the restarted server"),
     inv(replay_in_parallel, maps:get(peak_inflight, Replay) > 1,
         "the replay had more than one ProxyRegister in flight at the server at once"),
     inv(no_lost_disconnected, Lost =:= 0,
         "every DISCONNECTED raised during the outage reached the server after it"),
     inv(every_live_session_connected, maps:get(missing_connected, Conv) =:= 0,
         "the restarted server holds a CONNECTED notice for every live session")];
invariants(gateway_crash, R) ->
    [inv(all_reregistered, maps:get(all_reregistered, R),
         "every agent registered again with the new gateway"),
     inv(no_register_failures_after_restart, maps:get(register_failures_after_restart, R) =:= 0,
         "no Register attempt to the new gateway failed"),
     inv(every_live_session_connected,
         maps:get(missing_connected, maps:get(convergence, R)) =:= 0,
         "the server holds a CONNECTED notice for every live session")];
invariants(planned_stop, R) ->
    [inv(no_lost_disconnected, maps:get(disconnected_lost, R) =:= 0,
         "the server received a DISCONNECTED notice for every session on a planned stop")];
invariants(fanout, R) ->
    #{fanout := F} = R,
    [inv(every_command_answered, maps:get(answered, F) =:= maps:get(targets, F),
         "every agent's answer reached the management client"),
     inv(mgmt_connection_kept, maps:get(connection_drops, F) =:= 0,
         "the management connection was never closed during the fan-out"),
     inv(no_agent_disconnects, maps:get(agent_disconnects_during, R) =:= 0,
         "no agent lost its session during the fan-out")].

registration_invariants(R) ->
    #{register := Reg, upstream := Up, convergence := Conv, settle := Settle} = R,
    [inv(no_first_attempt_failures, maps:get(first_attempt_failed, Reg) =:= 0,
         "every agent's first Register succeeded (inside the agent's 30 s deadline)"),
     inv(all_registered_within_budget, maps:get(unregistered_at_budget, Reg) =:= 0,
         "every agent was registered within the scenario budget"),
     inv(upstream_register_in_parallel, maps:get(register_peak_inflight, Up) > 1,
         "more than one ProxyRegister was in flight at the server at once"),
     inv(no_wasted_upstream_registers, maps:get(wasted_register_rpcs, Up) =:= 0,
         "no ProxyRegister created a session at the server for an attempt that failed"),
     inv(every_live_session_connected, maps:get(missing_connected, Conv) =:= 0,
         "the server holds a CONNECTED notice for every live session"),
     inv(singleton_mailboxes_drain, maps:get(mailboxes_drained, Settle),
         "every named singleton's mailbox was back to 0 after the run")].

inv(Name, Ok, What) ->
    #{name => Name, ok => Ok, what => list_to_binary(What)}.

