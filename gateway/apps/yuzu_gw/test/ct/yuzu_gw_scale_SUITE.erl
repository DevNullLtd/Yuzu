%% Register outcomes and latency since T0, the server's view, the gateway's.
registration_report(Config, T0, Reg) ->
    registration_report(Config, T0, Reg, ?config(n, Config)).

%% Expected: how many agents should have registered since T0 (all N for ramp
%% and storm; for a phase where only some agents register, the ones that tried).
registration_report(Config, T0, Reg, Expected0) ->
    N = ?config(n, Config),
    Attempts = [A || {_, _, Start, _, _} = A <- load_call(Config, attempts, []), Start >= T0],
    ByAgent = group_attempts(Attempts),
    Firsts = [hd(L) || L <- maps:values(ByAgent)],
    FirstOk = [E - S || {_, _, S, E, ok} <- Firsts],
    FirstFailed = [A || {_, _, _, _, O} = A <- Firsts, O =/= ok],
    AllOk = [E - S || {_, _, S, E, ok} <- Attempts],
    Budget = budget(N),
    RegisteredBy = [lists:min([E || {_, _, _, E, ok} <- L] ++ [infinity])
                    || L <- maps:values(ByAgent)],
    Expected = case Expected0 of attempting -> maps:size(ByAgent); E -> E end,
    LateOrNever = length([1 || T <- RegisteredBy, T =:= infinity orelse T > T0 + Budget])
                  + max(0, Expected - maps:size(ByAgent)),
    Status = load_call(Config, status, []),
    Up = up_call(Config, stats, []),
    Waste = upstream_waste(up_call(Config, registers, []), Attempts, T0),
    Reg#{register => #{agents => N,
                       attempts => length(Attempts),
                       first_attempt_ok => length(FirstOk),
                       first_attempt_failed => length(FirstFailed),
                       first_attempt_failure_reasons => reasons(FirstFailed),
                       unregistered_at_budget => LateOrNever,
                       budget_ms => Budget,
                       first_attempt_latency_ms => stats(FirstOk),
                       ok_attempt_latency_ms => stats(AllOk),
                       live_now => maps:get(live, Status)},
         fleet => maps:merge(maps:without([by_state], Status),
                             #{by_state => maps:get(by_state, Status),
                               counters => load_call(Config, counters, [])}),
         upstream => maps:merge(Up, Waste),
         convergence => convergence(Config),
         gateway => gateway_report(Config)}.

%% The server's fresh ProxyRegister calls since T0, matched to the agent attempt
%% each belongs to (the attempt number rides in the request, see
%% yuzu_gw_scale_fleet:encode_attempt/2):
%%   wasted  the server created a session the agent never got: the attempt did
%%           not succeed;
%%   stale   of those, the call reached the server after the attempt had
%%           already ended: work started for a caller that had given up. (Every
%%           node reads the same OS clock, so no slack is needed; a call that
%%           started just before the agent gave up is wasted but not stale.)
upstream_waste(Registers, Attempts, T0) ->
    ByKey = maps:from_list([{{Id, N}, {End, Outcome}} || {Id, N, _S, End, Outcome} <- Attempts]),
    Fresh = [{Id, Recv, Att} || {Id, fresh, Recv, _Done, _S, Att} <- Registers, Recv >= T0],
    Wasted = [{Recv, End} || {Id, Recv, Att} <- Fresh,
                             {End, Outcome} <- [maps:get({Id, Att}, ByKey, {undefined, none})],
                             Outcome =/= ok],
    #{fresh_register_rpcs => length(Fresh),
      wasted_register_rpcs => length(Wasted),
      stale_register_rpcs => length([1 || {Recv, End} <- Wasted, is_integer(End), Recv > End])}.

group_attempts(Attempts) ->
    G = lists:foldl(fun({Id, _, _, _, _} = A, Acc) ->
                            maps:update_with(Id, fun(L) -> [A | L] end, [A], Acc)
                    end, #{}, Attempts),
    maps:map(fun(_, L) -> lists:keysort(3, L) end, G).

%% Does the server's view match the agents'? A live session with no CONNECTED
%% notice at the server is missing; a session the server last saw CONNECTED
%% that no agent holds is a ghost.
convergence(Config) ->
    Truth = truth(Config),
    Live = sets:from_list([S || {_, S, _} <- Truth], [{version, 2}]),
    Notices = up_call(Config, notices, []),
    Connected = sets:from_list([S || {_, S, connected, _} <- Notices], [{version, 2}]),
    Sessions = up_call(Config, sessions, []),
    Ghosts = length([1 || {S, _, connected} <- Sessions, not sets:is_element(S, Live)]),
    #{live_sessions => sets:size(Live),
      missing_connected => sets:size(sets:subtract(Live, Connected)),
      ghost_sessions => Ghosts}.

crash_progress(Config, KeptSessions, FlapOld, N) ->
    Registers = up_call(Config, registers, []),
    Replays = maps:from_list([{{Id, S}, Recv} || {Id, replay, Recv, _, S, _} <- Registers]),
    Hit = [maps:get(K, Replays) || K <- KeptSessions, maps:is_key(K, Replays)],
    Notices = up_call(Config, notices, []),
    FlapSet = sets:from_list(FlapOld, [{version, 2}]),
    FlapDisc = sets:size(sets:from_list([S || {_, S, disconnected, _} <- Notices,
                                              sets:is_element(S, FlapSet)], [{version, 2}])),
    Live = length(truth(Config)),
    Done = length(Hit) =:= length(KeptSessions) andalso FlapDisc =:= length(FlapOld)
        andalso Live =:= N,
    #{done => Done, replayed => length(Hit),
      replay_last_ms => lists:max([0 | Hit]), flap_disc => FlapDisc, live => Live}.

gateway_report(Config) ->
    #{probe => probe_report(Config),
      scheduler => probe_call(Config, sched_report, []),
      memory => gw_call(Config, ?PROBE, memory, []),
      memory_baseline => maps:get(mem_baseline, ?config(gw, Config)),
      registry_agents => gw_call(Config, yuzu_gw_registry, agent_count, []),
      memory_per_connection_bytes => mem_per_conn(Config),
      memory_per_connection_by_type => mem_per_conn_by_type(Config),
      agent_footprint => gw_call(Config, ?PROBE, footprint, [20])}.

%% (memory now - memory at boot) / registered agents, in total and by type.
mem_per_conn(Config) ->
    maps:get(total, mem_per_conn_by_type(Config), null).

mem_per_conn_by_type(Config) ->
    #{mem_baseline := Base} = ?config(gw, Config),
    Now = gw_call(Config, ?PROBE, memory, []),
    case gw_call(Config, yuzu_gw_registry, agent_count, []) of
        0 -> #{};
        Agents -> maps:from_list([{K, (maps:get(K, Now) - maps:get(K, Base)) div Agents}
                                  || K <- [total, processes, binary, ets, process_count]])
    end.

probe_report(Config) ->
    gw_call(Config, ?PROBE, report, []).

%% Wait until every named singleton's mailbox reads 0 and the server's counters
%% stop moving for a second (or the settle cap passes).
settle(Config) ->
    N = ?config(n, Config),
    T0 = erlang:system_time(millisecond),
    %% Heartbeat counters keep moving for as long as agents are connected; only
    %% registrations and notices have to stop.
    Moving = [register_rpcs, replay_rpcs, connected_notices, disconnected_notices],
    Check = fun() ->
                    S1 = maps:with(Moving, up_call(Config, stats, [])),
                    timer:sleep(1000),
                    S2 = maps:with(Moving, up_call(Config, stats, [])),
                    Boxes = gw_call(Config, ?PROBE, mailboxes, []),
                    Busy = maps:filter(fun(_, L) -> L > 0 end, Boxes),
                    case {S1 =:= S2, map_size(Busy)} of
                        {true, 0} -> {true, #{}};
                        _ -> {false, Busy}
                    end
            end,
    {Ok, Busy} = wait_until(Check, 30000 + 4 * N, 0),
    #{mailboxes_drained => Ok, still_busy => Busy,
      settle_ms => erlang:system_time(millisecond) - T0}.

%% Register N agents quickly (the server answers at once) before a scenario's
%% measured phase; returns how that went.
setup_registered(Config) ->
    N = ?config(n, Config),
    set_upstream(Config, #{register_latency_ms => {0, 0}}),
    T0 = erlang:system_time(millisecond),
    ok = load_call(Config, spawn_agents, [#{from => 1, count => N, mode => storm}]),
    Reg = await_registered(Config, N, T0),
    _ = settle(Config),
    probe_call(Config, reset_hwm, []),
    probe_call(Config, sched_mark, []),
    Reg#{memory_per_connection_bytes => mem_per_conn(Config),
         connected_notices => maps:get(connected_notices, up_call(Config, stats, []))}.

%% Wait until N agents are live (or the cap passes). Returns how long it took.
await_registered(Config, N, T0) ->
    {Reached, Live} = wait_until(fun() ->
                                         #{live := L} = load_call(Config, status, []),
                                         {L >= N, L}
                                 end, budget(N) * 3, 250),
    #{all_registered => Reached, live => Live,
      time_to_all_registered_ms => case Reached of
                                       true -> erlang:system_time(millisecond) - T0;
                                       false -> null
                                   end}.

