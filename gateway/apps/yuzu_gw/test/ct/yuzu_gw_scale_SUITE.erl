finish(Scenario, Config, R0) ->
    N = ?config(n, Config),
    Invs = invariants(Scenario, R0),
    Violated = [I || #{ok := false} = I <- Invs],
    R = R0#{scenario => Scenario, agents => N, invariants => Invs,
            time => list_to_binary(calendar:system_time_to_rfc3339(erlang:system_time(second)))},
    Dir = ?config(results_dir, Config),
    Order = integer_to_list(index_of(Scenario, cases())),
    File = filename:join(Dir, "yuzu_gw_scale-" ++ ?config(run, Config) ++ "-" ++ Order ++ "-"
                         ++ atom_to_list(Scenario) ++ ".json"),
    ok = file:write_file(File, json:encode(jsonable(R))),
    print(Scenario, N, R),
    ct:pal("~p N=~b: results in ~s", [Scenario, N, File]),
    case Violated of
        [] ->
            ok;
        _ ->
            Names = string:join([atom_to_list(maps:get(name, I)) || I <- Violated], ", "),
            Msg = lists:flatten(io_lib:format("~p N=~b: INVARIANT VIOLATED: ~s",
                                              [Scenario, N, Names])),
            [ct:pal("SCALE_INVARIANT_VIOLATED ~p ~p: ~s", [Scenario, maps:get(name, I),
                                                            maps:get(what, I)])
             || I <- Violated],
            case mode(Config) of
                gate -> ct:fail(Msg);
                report -> {comment, Msg ++ " (report mode: recorded, not failed)"}
            end
    end.

%% SCALE_METRIC lines, one number each: the headline ones on the console (and
%% so in the output scripts/test/perf-gate.sh parses), every one in the HTML log.
print(Scenario, N, R) ->
    Lines = [{lists:flatten(io_lib:format("scale_~s_n~b", [K, N])), num(V)}
             || {K, V} <- flatten(atom_to_list(Scenario), R)],
    Fmt = fun(L) -> lists:flatten([io_lib:format("SCALE_METRIC ~s=~s~n", [K, V]) || {K, V} <- L]) end,
    Headline = [L || {K, _} = L <- Lines, re:run(K, headline_re(), [{capture, none}]) =:= match],
    ct:pal("~s", [Fmt(Headline)]),
    ct:log("~s", [Fmt(Lines)]),
    ok.

