#!/usr/bin/env python3
"""Regenerate the plugin list the gateway scale suite registers with.

The gateway scale suite (gateway/apps/yuzu_gw/test/ct/yuzu_gw_scale_SUITE.erl)
sends each simulated agent's RegisterRequest with the plugin list a real agent
sends: one PluginInfo per plugin under agents/plugins/, with the name, version,
description and actions (capabilities) the plugin's descriptor declares (the
fields agents/core/src/agent.cpp copies into AgentInfo.plugins). The size of
that list is what makes a registration cost what it costs in the gateway (the
registry joins a pg group per plugin), so an empty or one-entry list hides it.

The values are read from the plugin sources with regular expressions, not by
building the plugins. A plugin whose descriptor is not in the usual shape is
kept with its directory name, version "1.0.0", an empty description and no
actions, so the count still matches agents/plugins/.

Usage (from the repository root):
    python3 scripts/test/gen-gateway-scale-register-fixture.py
writes gateway/apps/yuzu_gw/test/ct/yuzu_gw_scale_SUITE_data/register_plugins.eterm
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "gateway/apps/yuzu_gw/test/ct/yuzu_gw_scale_SUITE_data/register_plugins.eterm"

STR = r'"((?:[^"\\]|\\.)*)"'
NAME = re.compile(r'name\(\)\s*const\s*noexcept\s*override\s*\{\s*return\s*' + STR)
VERSION = re.compile(r'version\(\)\s*const\s*noexcept\s*override\s*\{\s*return\s*' + STR)
DESC = re.compile(r'description\(\)\s*const\s*noexcept\s*override\s*\{\s*return\s*((?:' + STR + r'\s*)+);')
ACTIONS = re.compile(r'actions\(\)\s*const\s*noexcept\s*override\s*\{.*?\{(.*?)nullptr', re.S)


def c_strings(text):
    return [bytes(s, "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")
            for s in re.findall(STR, text)]


def descriptor(plugin_dir):
    for src in sorted((plugin_dir / "src").glob("*.cpp")) if (plugin_dir / "src").is_dir() else []:
        text = src.read_text(encoding="utf-8", errors="replace")
        name = NAME.search(text)
        if not name:
            continue
        version = VERSION.search(text)
        desc = DESC.search(text)
        actions = ACTIONS.search(text)
        return {"name": name.group(1),
                "version": version.group(1) if version else "1.0.0",
                "description": "".join(c_strings(desc.group(1))) if desc else "",
                "capabilities": c_strings(actions.group(1)) if actions else []}
    return {"name": plugin_dir.name, "version": "1.0.0", "description": "", "capabilities": []}


def erl_bin(s):
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return '<<"%s"/utf8>>' % escaped


def main():
    plugins = [descriptor(d) for d in sorted((ROOT / "agents/plugins").iterdir()) if d.is_dir()]
    lines = ["%% -*- coding: utf-8 -*-",
             "%% GENERATED by scripts/test/gen-gateway-scale-register-fixture.py from",
             "%%%% agents/plugins/*/src. Do not edit; regenerate. %d plugins." % len(plugins),
             "{plugins, ["]
    for i, p in enumerate(plugins):
        caps = ", ".join(erl_bin(c) for c in p["capabilities"])
        sep = "," if i < len(plugins) - 1 else ""
        lines.append("  #{name => %s, version => %s,\n    description => %s,\n    capabilities => [%s]}%s"
                     % (erl_bin(p["name"]), erl_bin(p["version"]), erl_bin(p["description"]), caps, sep))
    lines.append("]}.")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s (%d plugins)" % (OUT.relative_to(ROOT), len(plugins)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
